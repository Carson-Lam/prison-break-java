    //Act method executes every once in a while
    public void act() {
        Random rand = new Random();
        //Paddle & Ball image handling
        paddleImage.setLocation(p1.getX(), p1.getY());
        ballImage.setLocation(b.getX(),b.getY());
        //Detect A and D key presses to move paddle
        //Calls DKeyPressed() and AKeyPressed() methods in Game (extended)
        //Add logical operator && in condition to restrict paddle within boundaries using getter methods
        if (DKeyPressed() && p1.getX() + p1.getWidth() < getFieldWidth()) {
            p1.moveRight();
        }

        if (AKeyPressed() && p1.getX() > 0) {
            p1.moveLeft();
        }

        //Detect collision between paddle and ball using .collides() method in GameObject
        //Add condition to verify Y value
        //Call bounceY() for ball in ball class
        if (b.collides(p1) && b.getDy() > 0) {
            b.bounceY();
            bounceDirection=rand.nextInt(3);
            if (bounceDirection == 1 || bounceDirection == 2) {
                b.setDx(b.getDx());
            } else {
                b.setDx(-b.getDx());
            }
        }

        //Detect collision between ball and top of field using getter method
        //Call bounceY() for ball in ball class
        if (b.getY() <= 0) {
            b.bounceY();
        }

        //Detect collision between ball and left of field using getter method
        //Call bounceX() for ball in ball class
        if (b.getX() <= 0) {
            b.bounceX();
        }

        //Detect collision between ball and right of field using getter method
        //Add width of ball so detection so right edge does not clip out of field
        //Call bounceX() for ball in ball class
        if (b.getX() + b.getWidth() >= getFieldWidth()) {
            b.bounceX();
        }

        //Check brick collision
        //Iterate through each row and column of brick using two for loops
        //Use previously established fields of row and col
        for (int i = 0; i < col; ++i) {
            for (int j = 0; j < row; ++j) {
                if (br[i][j].collides(b)) { //Check collision with collides()
                    br[i][j].move(2000, 2000); //move bricks off-screen
                    br[i][j].getBrickImage().setLocation(2000,2000);
                    remove(br[i][j].getBrickImage());  // Remove the brick image from the game
                    remove(br[i][j]); //Remove the brick that was collided with

                    //Setup bouncing randomness
                    b.bounceY();
                    bounceDirection=rand.nextInt(3);
                    if (bounceDirection == 1 || bounceDirection == 2) {
                        b.setDx(b.getDx());
                    } else {
                        b.setDx(-b.getDx());
                    }
                    bricksCount--; //Increment bricksCount field (used to detect new level)
                    score += 10; //Increment score by 10 per brick
                    scoreLabel.setText("Score:" + score); //Update score label with new score
                }
            }
        }

        //Check whether player has lost the game by calling the gameOver() method in a conditional statement
        if (gameOver()) {
            //Stop game when game over is true
            stopGame();

            //Set 'dead' ball icon
             ballImage.setIcon(ballIconDead);

            //Call hsUpdate at the start of gameOver method
            //Logs the score and compares it to high score
            try {
                hsUpdate();
            } catch (IOException e) { //Try catch exception generated by Intellij
                throw new RuntimeException(e); //Define block of code to handle errors in the try block
            }
            //Call restartMenu method to allow player to continue playing or quit
            restartMenu();
        }

        //Increment to new level when all bricks are destroyed
        if (bricksCount == 0) {
            cutscene(); //Call cutscene method to play cutsceene, increments timer
            bricksCount = -1; //Set bricksCount to -1 to ensure that cutscene is not played again
        }
        //Conditional statement in act method which increments cutscene time
        if (waittime > 0) {
            waittime--;
        } else if (waittime == 0) { //Check when waittime reaches 0 according to act timer
            setupNewLevel(); //Call setupNewLevel() to print bricks, reset positions, etc
            waittime = -1; //Set waittime to -1 to ensure that code block is not executed again
        }
    }

