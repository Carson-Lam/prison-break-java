    /***
     * restartMenu() method to display JOptionPane on game over
     */
    public void restartMenu() {
        String[] options = {"Start", "Close", "Reset high score"};
        //Uses HTML to arrange text on JOptionPane
        int input = JOptionPane.showOptionDialog(getContentPane(),
                "<html> ▪ You have died. <br/>" +
                        "▪ your score was: " + score +
                        "<br/>▪ Would you like to play again? <br/>",
                "Prison Break", JOptionPane.YES_NO_OPTION, JOptionPane.PLAIN_MESSAGE,
                null, options, options[0]);
        System.out.println("RESTART MENU INPUT: " + input);
        if (input == JOptionPane.NO_OPTION) { //Closes game if player selects no
            setVisible(false);
            System.exit(0);
        } else if (input == JOptionPane.YES_OPTION) {
            //Iterates through existing bricks
            //Removes all bricks to prepare for resetLevel() method, which builds new ones
            for (int i = 0; i < col; ++i) {
                for (int j = 0; j < row; ++j) {
                    br[i][j].move(2000, 2000);
                    br[i][j].getBrickImage().setLocation(2000,2000);
                    remove(br[i][j].getBrickImage());  // Remove the brick image from the game
                    remove(br[i][j]); //Remove the brick that was collided with
                }
            }
            //Call resetLevel() method to reset position of paddle and ball
            //Reset speed of ball, reset paddle state, reset level and score, and reset labels.
            resetLevel();
            startGame();
        } else if (input == 2){
            try {
                clearHS(); // Try clearing the high score
                restartMenu();
            } catch (IOException e) {
                e.printStackTrace(); // Print the error if something goes wrong
                JOptionPane.showMessageDialog(getContentPane(), "Error clearing high score. Please try again.");
            }
        }
    }

