    /***
     * setBricks method to put bricks on screen
     */
    public void setBricks() {
        //Sets row and col fields to lengths of the br array (setup earlier)
        col = br.length;
        row = br[0].length;
        bricksCount = row * col;
        //Center bricks on the field relative to field width
        int x = ((getFieldWidth() + 22) - (80 * col)) / 2;
        //Use two for loops incrementing up to row and col fields
        //Use incrementing variables i and j in br array to setup the brick objects
        //Increment position of brick object with each loop using compound assignment operators
        //to prevent the bricks from stacking on top of each other
        for (int i = 0; i < col; ++i) {
            int y = 22;
            for (int j = 0; j < row; ++j) {
                br[i][j] = new Bricks(brickIcon);
                add(br[i][j]);
                add(br[i][j].getBrickImage());
                br[i][j].setLocation(x, y);
                br[i][j].setSize(60, 30);
                y += 60;
            }
            x += 80;
        }
    }

    /***
     * setupNewLevel method for building new level after cutscene
     */
    public void setupNewLevel() {
        b.justifyDirection(); //Makes sure ball goes towards paddle with justifyDirection() method in ball
        //Unpause the ball and paddle using the setter methods after waittime from cutscene is up
        b.setBallPaused(false);
        p1.setPaddlePaused(false);
        //Speed up the ball and paddle
        b.accelerate();
        p1.setPaddleSpeed(p1.getPaddleSpeed() + b.getAccel());
        //Debugging paddle method - resets state of keypresses using method in Game
        resetPaddle();
        setBricks();
        levelLabel.setVisible(false);
        level++;
        levelShowcase.setText("Level:" + level); //Update level label on screen
    }

    /***
     * resetLevel method for first level after a game over
     * Reset position of paddle and ball using setter methods
     * Reset state of keypresses in paddle
     * Reset level and score
     * Update labels of score and level
     */
    public void resetLevel() {
        Random rand = new Random();
        bounceDirection = rand.nextInt(2);
        //Reset position of paddle and ball using setter methods
        p1.setX(getFieldWidth() / 2 - (p1.getWidth() / 2));
        p1.setY(getFieldHeight() * 6 / 7);
        p1.setPaddleSpeed(8);
        b.setX(getFieldWidth() / 2);
        b.setY(getFieldHeight() * 3 / 5);
        if (bounceDirection == 1) b.setDx(4);
        else b.setDx(-4);
        b.setDy(4);
        ballImage.setIcon(ballIcon);
        resetPaddle(); //Reset state of keypresses in paddle
        setBricks();
        //Reset level and score
        level = 1;
        score = 0;
//        System.out.println("POST RESET SCORE " + score);
//        System.out.println("POST RESET HS: " + highscore);
        //Update labels of score and level
        scoreLabel.setText("Score:" + score);
        levelShowcase.setText("Level:" + level);
    }

    /***
     * Method to update high score by comparing ending score with current standing high score
     * Called when player loses and score is finalized
     * File is overwritten if new score exceeds current high score
     * Research and sources used
     * https://www.w3schools.com/java/java_files_create.asp
     * https://www.digitalocean.com/community/tutorials/java-write-to-file
     * @throws IOException
     */
    public void hsUpdate() throws IOException {
//        System.out.println("SCORE " + score);
//        System.out.println("HS: " + highscore);
        if (score > highscore) {
//            System.out.println("SCORE: " + score);
//            System.out.println("HS: " + highscore);
            File file = new File("highscore.txt");
            FileWriter writer = new FileWriter(file);
            highscore = score;
            writer.write(String.valueOf(score));
            hsLabel.setText("HS:" + highscore);
            writer.close();
        }
    }

    public void clearHS() throws IOException {
        File file = new File("highscore.txt");
        FileWriter writer = new FileWriter(file);
//        score = 0;
        highscore = 0;
//        System.out.println("ClearHS SCORE: " + score);
//        System.out.println("ClearHS HS: " + highscore);
        writer.write("0");
        writer.close();
        hsLabel.setText("HS:" + highscore);
    }

    /***
     * readFile() method to retrieve existing high score from file
     * Called in game setup, sets highscore field to number in file
     * @throws IOException
     */
    public static void readFile() throws IOException {
        File file = new File("highscore.txt");
        if (file.exists()) { //Condition to check whether highscore file already exists
            Scanner sc = new Scanner(file);
            if (sc.hasNextInt()) { //Scanner checks value inside file
                highscore = sc.nextInt();
            } else { //If no value found, new writer is created and 0 is written into the file
                FileWriter write = new FileWriter("highscore.txt", false);
                write.write("0");
                write.close();
            }
        } else {
            file.createNewFile(); //If no highscore file already exists, a new one is created
            FileWriter write = new FileWriter("highscore.txt", false);
            write.write("0"); //0 is also written into the new file
            write.close();
        }
    }

