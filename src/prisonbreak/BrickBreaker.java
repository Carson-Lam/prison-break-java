    /***
     * GameOver method to check death
     * @return true or false
     */
    public boolean gameOver() {
        //Check if ball's y exceeds that of paddle + paddle's height at the bottom
        if (b.getY() >= p1.getY() + p1.getHeight()) {
            return true;
        } else {
            return false;
        }
    }

